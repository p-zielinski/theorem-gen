"""Export the supported Lean 4 subset. The exporter does not change meaning."""

from __future__ import annotations

import re
from typing import Sequence

from theorem_gen.config import GeneratorConfig
from theorem_gen.errors import ExportError
from theorem_gen.expr import (
    Atom,
    BinOp,
    Compare,
    Const,
    Forall,
    Implies,
    IntLit,
    NatLit,
    UnaryOp,
    Var,
)
from theorem_gen.theorem import Theorem

_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_']*$")
_KEYWORDS = {
    "axiom",
    "def",
    "lemma",
    "opaque",
    "sorry",
    "theorem",
    "unsafe",
}

_BANNER = """/-
Generated by theorem-gen. Concrete Nat theorems only.
The header comments record the seed and configuration.
-/
"""

_EXTENDED_BANNER = """/-
Generated by theorem-gen. Typed definitions, theorems, and checked expressions.
The header comments record the seed and configuration.
-/
"""


def export_expr(expr: object) -> str:
    if isinstance(expr, NatLit):
        return str(expr.value)
    if isinstance(expr, IntLit):
        return f"({expr.value} : Int)"
    if isinstance(expr, Var):
        return expr.name
    if isinstance(expr, UnaryOp):
        if expr.op == "succ":
            return f"(Nat.succ {export_expr(expr.arg)})"
        return f"(-{export_expr(expr.arg)})"
    if isinstance(expr, BinOp):
        symbol = "+" if expr.op == "add" else "*"
        return f"({export_expr(expr.left)} {symbol} {export_expr(expr.right)})"
    if isinstance(expr, Const):
        if not expr.args:
            return expr.name
        arguments = " ".join(export_expr(arg) for arg in expr.args)
        return f"({expr.name} {arguments})"
    raise ExportError("expected an expression")


def export_prop(prop: object) -> str:
    if isinstance(prop, Compare):
        symbol = {"eq": "=", "le": "<=", "lt": "<"}[prop.op]
        return f"({export_expr(prop.left)} {symbol} {export_expr(prop.right)})"
    if isinstance(prop, Implies):
        return f"({export_prop(prop.premise)} -> {export_prop(prop.conclusion)})"
    if isinstance(prop, Atom):
        if not prop.args:
            return prop.name
        arguments = " ".join(export_expr(arg) for arg in prop.args)
        return f"({prop.name} {arguments})"
    raise ExportError("expected a proposition")


def export_theorem(theorem: Theorem) -> str:
    _require_name(theorem)
    kind = theorem.metadata.kind
    if kind == "expression":
        if theorem.proof is not None:
            raise ExportError(f"{theorem.metadata.identifier} is an expression and has no proof")
        return _export_expression(theorem)
    if kind == "concrete":
        if theorem.proof is None:
            raise ExportError(f"{theorem.metadata.identifier} has no proof")
        proposition = export_prop(theorem.statement)
        return f"theorem {theorem.metadata.identifier} : {proposition} {_proof_text(theorem.proof)}"
    if kind == "universal":
        return _export_quantified(theorem, conditional=False)
    if kind == "conditional":
        return _export_quantified(theorem, conditional=True)
    raise ExportError(
        f"unsupported theorem kind for export: {kind} "
        "(supported: concrete, universal, conditional, expression)"
    )


def export_definition(definition) -> str:
    params = " ".join(f"({item.name} : {item.type_name})" for item in definition.params)
    gap = " " if params else ""
    return (
        f"def {definition.name}{gap}{params} : {definition.result_type} "
        f":= {export_expr(definition.body)}"
    )


def export_module(theorems: Sequence[Theorem], config: GeneratorConfig) -> str:
    return export_library((), theorems, config)


def export_library(definitions: Sequence, theorems: Sequence[Theorem], config: GeneratorConfig) -> str:
    items = tuple(theorems)
    if len(items) != config.count:
        raise ExportError(
            f"module has {len(items)} theorems but config.count is {config.count}"
        )
    names = [item.metadata.identifier for item in items]
    names.extend(definition.name for definition in definitions)
    if len(names) != len(set(names)):
        raise ExportError("duplicate theorem identifiers")
    header = [
        f"-- theorem-gen seed: {config.seed}",
        f"-- theorem-gen count: {config.count}",
        f"-- theorem-gen max_literal: {config.max_literal}",
        f"-- theorem-gen max_depth: {config.max_depth}",
        f"-- theorem-gen max_value: {config.max_value}",
        f"-- theorem-gen unique: {str(config.unique).lower()}",
        f"-- theorem-gen max_attempts: {config.effective_max_attempts()}",
        "-- theorem-gen rules: " + ",".join(config.resolved_rules()),
    ]
    if config.complexity_bounds:
        rendered = ",".join(
            f"{key}:{low}-{high}" for key, (low, high) in sorted(config.complexity_bounds.items())
        )
        header.append(f"-- theorem-gen complexity: {rendered}")
    extended = bool(definitions) or any(
        theorem.metadata.kind != "concrete" for theorem in items
    )
    text = (_EXTENDED_BANNER if extended else _BANNER) + "\n".join(header) + "\n"
    blocks = [export_definition(definition) for definition in definitions]
    blocks.extend(export_theorem(theorem) for theorem in items)
    if blocks:
        text += "\n" + "\n\n".join(blocks) + "\n"
    return text


def _export_expression(theorem: Theorem) -> str:
    statement = theorem.statement
    if isinstance(statement, Forall):
        binders = " ".join(
            f"({item.name} : {item.type_name})" for item in statement.binders
        )
        body = export_prop(statement.body)
        rendered = f"forall {binders}, {body}"
    else:
        rendered = export_prop(statement)
    return "\n".join(
        (
            f"-- expression {theorem.metadata.identifier} kind=expression",
            f"#check ({rendered})",
            "-- This expression has no proof and is not claimed true.",
        )
    )


def _export_quantified(theorem: Theorem, conditional: bool) -> str:
    if theorem.proof is None:
        raise ExportError(f"{theorem.metadata.identifier} has no proof")
    statement = theorem.statement
    if not isinstance(statement, Forall):
        raise ExportError("quantified theorem expects a forall")
    binders = " ".join(f"({item.name} : {item.type_name})" for item in statement.binders)
    body = statement.body
    hypothesis = ""
    if conditional:
        if not isinstance(body, Implies):
            raise ExportError("conditional theorem expects an implication")
        hypothesis = f" (h : {export_prop(body.premise)})"
        body = body.conclusion
    return (
        f"theorem {theorem.metadata.identifier} {binders}{hypothesis} : "
        f"{export_prop(body)} {_proof_text(theorem.proof)}"
    )


def _proof_text(proof) -> str:
    if proof.method == "rfl":
        return ":= rfl"
    if proof.method == "decide":
        return ":= by\n  decide"
    if proof.method == "lemma":
        arguments = " ".join(proof.arguments)
        target = proof.reference if not arguments else f"{proof.reference} {arguments}"
        return f":= {target}"
    if proof.method == "rewrite":
        return f":= by\n  rw [{proof.reference}]\n  exact {proof.arguments[0]}"
    raise ExportError(f"unsupported proof method: {proof.method}")


def _require_name(theorem: Theorem) -> None:
    if not isinstance(theorem, Theorem):
        raise ExportError("expected a theorem")
    name = theorem.metadata.identifier
    if name in _KEYWORDS or not _IDENT.match(name):
        raise ExportError(f"invalid Lean identifier: {name}")
