import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from theorem_gen.config import DEFAULT_RULES, GeneratorConfig
from theorem_gen.errors import ExportError, TheoremError
from theorem_gen.expr import BinOp, Compare, NatLit
from theorem_gen.export_lean import export_expr, export_module, export_prop, export_theorem
from theorem_gen.theorem import Metadata, Proof, Theorem


def meta(identifier="gen_s1_0000", rules=("add_zero",), kind="concrete"):
    return Metadata(
        identifier=identifier,
        kind=kind,
        rules=rules,
        verification="unverified",
    )


def theorem(statement, proof, identifier="gen_s1_0000", kind="concrete"):
    return Theorem(statement=statement, proof=proof, metadata=meta(identifier, kind=kind))


class ExportTests(unittest.TestCase):
    def test_expressions_are_fully_parenthesized(self):
        expr = BinOp("mul", BinOp("add", NatLit(2), NatLit(3)), NatLit(4))
        self.assertEqual(export_expr(NatLit(2)), "2")
        self.assertEqual(export_expr(expr), "((2 + 3) * 4)")
        self.assertNotEqual(export_expr(expr), "(2 + 3 * 4)")

    def test_propositions_use_ascii_comparisons(self):
        self.assertEqual(
            export_prop(Compare("eq", BinOp("add", NatLit(2), NatLit(3)), NatLit(5))),
            "((2 + 3) = 5)",
        )
        self.assertEqual(export_prop(Compare("le", NatLit(2), NatLit(5))), "(2 <= 5)")
        self.assertEqual(export_prop(Compare("lt", NatLit(2), NatLit(5))), "(2 < 5)")

    def test_proof_method_is_not_rewritten(self):
        equality = theorem(Compare("eq", NatLit(1), NatLit(1)), Proof("decide"))
        inequality = theorem(Compare("le", NatLit(1), NatLit(1)), Proof("rfl"))
        self.assertEqual(export_theorem(equality), "theorem gen_s1_0000 : (1 = 1) := by\n  decide")
        self.assertNotIn("rfl", export_theorem(equality))
        self.assertEqual(export_theorem(inequality), "theorem gen_s1_0000 : (1 <= 1) := rfl")
        self.assertNotIn("decide", export_theorem(inequality))

    def test_false_statement_is_exported_unchanged(self):
        text = export_theorem(theorem(Compare("eq", NatLit(1), NatLit(0)), Proof("rfl")))
        self.assertEqual(text, "theorem gen_s1_0000 : (1 = 0) := rfl")
        self.assertNotIn("1 = 1", text)

    def test_module_format_records_the_configuration(self):
        config = GeneratorConfig(seed=1, count=2, rules=("add_zero",))
        theorems = (
            theorem(Compare("eq", BinOp("add", NatLit(2), NatLit(3)), NatLit(5)), Proof("rfl")),
            theorem(
                Compare("le", NatLit(2), NatLit(5)),
                Proof("decide"),
                identifier="gen_s1_0001",
            ),
        )
        self.assertEqual(
            export_module(theorems, config),
            """/-
Generated by theorem-gen. Concrete Nat theorems only.
The header comments record the seed and configuration.
-/
-- theorem-gen seed: 1
-- theorem-gen count: 2
-- theorem-gen max_literal: 9
-- theorem-gen max_depth: 2
-- theorem-gen max_value: 10000
-- theorem-gen unique: true
-- theorem-gen max_attempts: 200
-- theorem-gen rules: add_zero

theorem gen_s1_0000 : ((2 + 3) = 5) := rfl

theorem gen_s1_0001 : (2 <= 5) := by
  decide
""",
        )

    def test_empty_module_and_default_rules(self):
        text = export_module([], GeneratorConfig(seed=1, count=0, rules=("add_zero",)))
        self.assertTrue(text.endswith("-- theorem-gen rules: add_zero\n"))
        self.assertNotIn("theorem ", text)
        self.assertIn("-- theorem-gen max_attempts: 100\n", text)
        defaults = export_module([], GeneratorConfig(seed=1, count=0))
        self.assertIn("-- theorem-gen rules: " + ",".join(DEFAULT_RULES), defaults)

    def test_count_mismatch_and_duplicate_names_are_rejected(self):
        thm = theorem(Compare("eq", NatLit(1), NatLit(1)), Proof("rfl"))
        with self.assertRaises(ExportError):
            export_module((thm,), GeneratorConfig(seed=1, count=2, rules=("add_zero",)))
        with self.assertRaises(ExportError):
            export_module((thm, thm), GeneratorConfig(seed=1, count=2, rules=("add_zero",)))

    def test_missing_proof_bad_name_and_non_concrete_kind_are_rejected(self):
        statement = Compare("eq", NatLit(1), NatLit(1))
        with self.assertRaises(ExportError):
            export_theorem(Theorem(statement, None, meta()))
        with self.assertRaises(ExportError):
            export_theorem(theorem(statement, Proof("rfl"), identifier="1bad"))
        with self.assertRaises(ExportError):
            export_theorem(theorem(statement, Proof("rfl"), identifier="theorem"))
        with self.assertRaises(ExportError) as caught:
            export_theorem(theorem(statement, Proof("rfl"), kind="forall"))
        self.assertIn("unsupported theorem kind for export: forall", str(caught.exception))
        self.assertIn("concrete, universal, conditional, expression", str(caught.exception))
        self.assertNotIn("only concrete theorems can be exported", str(caught.exception))

    def test_sorry_is_not_a_proof_method(self):
        with self.assertRaises(TheoremError):
            Proof("sorry")

    def test_export_expr_rejects_a_proposition(self):
        with self.assertRaises(ExportError):
            export_expr(Compare("eq", NatLit(1), NatLit(1)))


if __name__ == "__main__":
    unittest.main()
