def _action(**overrides):
    values = dict(
        untrained=0,
        epoch=1,
        hold=False,
        lean_backlog=0,
        high_water=128,
        loss_ready=False,
        burst_left=0,
    )
    values.update(overrides)
    return choose_action(**values)


class BalanceTests(unittest.TestCase):
    def test_unread_rows_keep_training_until_loss_opens_a_burst(self):
        self.assertEqual(_action(untrained=3, epoch=2), "train")
        self.assertEqual(_action(untrained=0, epoch=0), "train")
        self.assertFalse(loss_is_ready([0.3] * 9))
        self.assertFalse(loss_is_ready([0.3] * 9 + [0.45]))
        self.assertTrue(loss_is_ready([0.3] * 10))

    def test_a_ready_burst_writes_while_rows_remain(self):
        self.assertEqual(_action(untrained=100, epoch=0, loss_ready=True, burst_left=10), "sample")
        burst, study = open_burst(0, 0, True)
        self.assertEqual((burst, study), (SAMPLE_BURST, 0))
        burst, study = after_sample(1, 0, "queued")
        self.assertEqual((burst, study), (0, STUDY_STEPS))
        burst, study = after_sample(4, 0, "duplicate")
        self.assertEqual((burst, study), (4, 0))
        self.assertEqual(after_train(STUDY_STEPS, True), STUDY_STEPS - 1)
        self.assertEqual(after_train(3, False), 0)
        self.assertEqual(after_train(5, False, waiting=True), 5)
        self.assertEqual(open_burst(0, 5, True), (0, 5))

    def test_weak_window_returns_to_rehearsal(self):
        streak = 0
        hold = False
        for _ in range(8):
            streak, hold = observe("duplicate", streak)
        self.assertTrue(hold)
        self.assertEqual(streak, 8)
        self.assertEqual(_action(hold=True, loss_ready=True, burst_left=10), "rehearse")
        streak, hold = observe("proved", streak)
        self.assertEqual((streak, hold), (0, False))

    def test_full_lean_queue_waits(self):
        self.assertEqual(_action(loss_ready=True, burst_left=3, lean_backlog=128), "wait")
        self.assertEqual(_action(loss_ready=True, burst_left=3, lean_backlog=0), "sample")

    def test_the_write_card_shows_the_current_stage(self):
        self.assertEqual(loss_streak([0.2, 0.7, 0.1, 0.2]), 2)
        self.assertEqual(loss_streak([0.1] * 12), 10)
        label, hint = write_card(
            hold=False, burst_left=0, study_left=0, streak=0, model_backlog=0, last_loss=0.746
        )
        self.assertEqual(label, "0/10")
        self.assertIn("0.746", hint)
        label, hint = write_card(
            hold=False, burst_left=0, study_left=0, streak=4, model_backlog=0, last_loss=0.3
        )
        self.assertEqual(label, "4/10")
        self.assertIn("4 updates in a row", hint)
        label, hint = write_card(
            hold=False, burst_left=7, study_left=0, streak=10, model_backlog=0
        )
        self.assertEqual(label, "Yes")
        self.assertIn("7 of 10", hint)
        label, hint = write_card(
            hold=False, burst_left=7, study_left=0, streak=10, model_backlog=128
        )
        self.assertEqual(label, "Waiting")
        self.assertIn("not spent", hint)
        label, hint = write_card(
            hold=False, burst_left=0, study_left=142, streak=0, model_backlog=0
        )
        self.assertEqual(label, "Studying")
        self.assertIn("142 study steps", hint)
        label, _hint = write_card(
            hold=True, burst_left=10, study_left=0, streak=10, model_backlog=0
        )
        self.assertEqual(label, "No")

    def test_ten_queued_equations_then_study(self):
        with tempfile.TemporaryDirectory() as tmp:
            engine = make_engine(tmp, max_steps=0)
            engine.start()
            service = MiniLMService(Path(tmp) / "lm", TINY)
            service._load_state(engine.store, "run-1")
            service.recent_losses = [0.3] * 10
            service._save_state(engine.store, "run-1")
            samples = []

            def fake_sample(_engine):
                samples.append("sample")
                return "queued"

            trains = []

            def fake_train(_engine, after, advance_cursor):
                trains.append((after, advance_cursor))
                return "trained"

            service._sample = fake_sample
            service._train_page = fake_train
            for _ in range(SAMPLE_BURST):
                service.tick(engine)
            self.assertEqual(len(samples), SAMPLE_BURST)
            self.assertEqual(trains, [])
            self.assertEqual(service.burst_left, 0)
            self.assertEqual(service.study_left, STUDY_STEPS)
            service.tick(engine)
            self.assertEqual(len(samples), SAMPLE_BURST)
            self.assertEqual(len(trains), 1)
            self.assertEqual(service.study_left, STUDY_STEPS - 1)


class RoleTests(unittest.TestCase):
    def test_header_is_not_the_equation(self):
        docs = role_documents(SOURCE)
        self.assertEqual(len(docs), 2)
        self.assertTrue(docs[0].startswith("<|propose|>"))
        self.assertNotIn(":=", docs[0].split("<|end|>")[0].split("\n", 1)[1])
        self.assertIn(":= rfl", docs[1])
        self.assertNotIn("Generated by", docs[0])
        body = equation_body(theorem_line(SOURCE))
        self.assertEqual(body, "(((7 + 6) + (5 + 2)) = 20)")

    def test_a_multiline_proof_stays_in_the_prove_document(self):
        source = (
            "theorem rich_s1_0003 (a : Nat) : ((a + 0) = a) := by\n"
            "  conv =>\n"
            "    lhs\n"
            "    rw [Nat.add_zero]\n"
            "  ac_rfl\n"
        )
        docs = role_documents(source)
        self.assertNotIn("ac_rfl", docs[0])
        self.assertIn("rw [Nat.add_zero]", docs[1])
        self.assertIn("ac_rfl", docs[1])

    def test_duplicate_body_is_not_queued(self):
        with tempfile.TemporaryDirectory() as tmp:
            engine = make_engine(tmp, max_steps=0)
            engine.start()
            service = MiniLMService(Path(tmp) / "lm", TINY)
            service.tick(engine)
            body = "(((7 + 6) + (5 + 2)) = 20)"
            digest = equation_hash(body)
            service.seen.add(digest)
            service.epoch = 1
            service._record(engine, body, digest, "duplicate", None)
            queued = engine.store.count_where(
                "SELECT COUNT(*) FROM queue_jobs WHERE run_id='run-1' AND idempotency_key LIKE '%model%'",
                (),
            )
            self.assertEqual(queued, 0)
            self.assertEqual(service.weak_streak, 1)
            self.assertFalse(learning_claimed(engine.store))

    def test_fresh_equation_is_checked_and_marked_model(self):
        with tempfile.TemporaryDirectory() as tmp:
            engine = make_engine(tmp, max_steps=0)
            engine.start()
            service = MiniLMService(Path(tmp) / "lm", TINY)
            service._load_state(engine.store, "run-1")
            body = "(1 + 1 = 2)"
            service._enqueue(engine, body, equation_hash(body), "theorem model_eq : (1 + 1 = 2) := rfl")
            row = engine.store._one("SELECT provenance, structural_hash FROM candidates WHERE family='model'")
            self.assertIn('"origin": "model"', row["provenance"])
            job = engine.store._one(
                "SELECT payload_json FROM queue_jobs WHERE idempotency_key LIKE '%model%'"
            )
            self.assertIn("1 + 1 = 2", job["payload_json"])
            attempt = engine.store._one("SELECT disposition FROM model_attempts")
            self.assertEqual(attempt["disposition"], "queued")
            self.assertIsNone(
                engine.store._one("SELECT name FROM sqlite_master WHERE name='qlora_state'")
            )

    def test_proved_model_row_clears_the_brake(self):
        with tempfile.TemporaryDirectory() as tmp:
            engine = make_engine(tmp, max_steps=0)
            engine.start()
            service = MiniLMService(Path(tmp) / "lm", TINY)
            service._load_state(engine.store, "run-1")
            service.weak_streak = 7
            service.hold = True
            body = "(0 = 0)"
            service._enqueue(engine, body, equation_hash(body), "theorem model_eq : (0 = 0) := rfl")
            candidate = engine.store._one("SELECT * FROM candidates WHERE family='model'")
            now = engine.store.now()
            engine.store.conn.execute(
                """
                INSERT INTO validations (
                  candidate_id, attempt_id, lean_version, toolchain_hash, validation_type,
                  result, accepted, stdout, stderr, message, failure_class, idempotency_key, created_at
                ) VALUES (?, NULL, 'fixture', 'fixture', 'proof', 'accepted', 1, '', '', '', NULL, ?, ?)
                """,
                (candidate["id"], "val-model", now),
            )
            engine.store.recompute(candidate["id"])
            fresh = engine.store.get_candidate(candidate["id"])
            service.note_verdict(engine.store, fresh)
            self.assertEqual(fresh["current_status"], "proved")
            self.assertEqual(service.weak_streak, 0)
            self.assertFalse(service.hold)
            saved = engine.store._one("SELECT disposition FROM model_attempts WHERE candidate_id=?", (candidate["id"],))
            self.assertEqual(saved["disposition"], "proved")


class ContextLimitTests(unittest.TestCase):
    def test_marks_count_toward_the_window(self):
        self.assertEqual(token_length("<|prove|>\n<|end|>"), 3)
        self.assertEqual(token_length("<|propose|>\nx\n<|end|>"), 5)
        text = "<|prove|>\ntheorem t : (0 = 0) := rfl\n<|end|>"
        from theorem_gen.learn.minilm import encode

        self.assertEqual(token_length(text), encode(text, 1000)[1])

    def test_an_overlong_sentence_waits_until_the_window_grows(self):
        short = "theorem s : (0 = 0) := rfl\n"
        long = "theorem long_marker : (" + " + ".join(["1"] * 30) + " = 30) := by\n  ac_rfl\n"
        short_len = max(token_length(doc) for doc in role_documents(short))
        long_len = max(token_length(doc) for doc in role_documents(long))
        self.assertGreater(long_len, short_len)

        class Window:
            def __init__(self, context):
                self.context = context

        with tempfile.TemporaryDirectory() as tmp:
            engine = make_engine(tmp, max_steps=0)
            engine.start()
            _plant(engine, "short-sentence", short)
            _plant(engine, "long-sentence", long)
            service = MiniLMService(Path(tmp) / "lm", Window(short_len))
            fitted = []

            def fake_fit(docs):
                fitted.extend(docs)
                return 0.2

            service._fit = fake_fit
            service._train_page(engine, after=0, advance_cursor=True)
            self.assertTrue(any("theorem s " in doc for doc in fitted))
            self.assertFalse(any("long_marker" in doc for doc in fitted))
            self.assertTrue(all(token_length(doc) <= short_len for doc in fitted))
            blocked = engine.store._one("SELECT * FROM context_blocks")
            self.assertEqual(blocked["status"], "blocked by context limit")
            self.assertEqual(blocked["token_length"], long_len)
            self.assertEqual(blocked["context_limit"], short_len)
            self.assertEqual(service.epoch, 0)
            self.assertEqual(snapshot(engine.store.path, "run-1")["context_blocked"], 1)

            service.config = Window(long_len)
            fitted.clear()
            service._train_page(engine, after=service.cursor_id, advance_cursor=True)
            self.assertTrue(any("long_marker" in doc for doc in fitted))
            self.assertTrue(all(token_length(doc) <= long_len for doc in fitted))
            self.assertIsNone(engine.store._one("SELECT candidate_id FROM context_blocks"))
            self.assertEqual(service.epoch, 0)
            service._train_page(engine, after=service.cursor_id, advance_cursor=True)
            self.assertEqual(service.epoch, 1)
            self.assertEqual(snapshot(engine.store.path, "run-1")["context_blocked"], 0)

    def test_the_cursor_waits_at_an_unfinished_check(self):
        with tempfile.TemporaryDirectory() as tmp:
            engine = make_engine(tmp, max_steps=0)
            engine.start()
            for name in ("a_closed", "b_closed", "c_closed", "d_closed"):
                _plant(engine, name, f"theorem {name} : (0 = 0) := rfl\n")
            _plant(engine, "in-flight", "theorem in_flight : (1 = 1) := rfl\n", proved=False)
            _plant(engine, "after-hole", "theorem after_hole : (2 = 2) := rfl\n")
            service = MiniLMService(Path(tmp) / "lm", type("W", (), {"context": 512})())
            fitted = []
            service._fit = lambda docs: fitted.extend(docs) or 0.1
            service.study_left = 5
            outcome = service._train_page(engine, after=0, advance_cursor=True)
            self.assertEqual(outcome, "trained")
            text = "\n".join(fitted)
            self.assertIn("a_closed", text)
            self.assertIn("d_closed", text)
            self.assertNotIn("after_hole", text)
            parked = service.cursor_id
            step = service.step
            seen = len(fitted)
            self.assertEqual(
                service._train_page(engine, after=service.cursor_id, advance_cursor=True),
                "waiting",
            )
            self.assertEqual(len(fitted), seen)
            self.assertEqual(service.cursor_id, parked)
            self.assertEqual(service.step, step)
            self.assertEqual(service.epoch, 0)
            self.assertEqual(after_train(service.study_left, False, waiting=True), 5)
            fitted.clear()
            engine.store.conn.execute(
                "UPDATE queue_jobs SET state='done' WHERE idempotency_key LIKE '%in-flight%'"
            )
            engine.store.insert_validation(
                candidate_id=engine.store.get_by_stable("in-flight")["id"],
                idempotency_key="val-in-flight-done",
                lean_version="fixture",
                toolchain_hash="fixture",
                validation_type="proof",
                result="accepted",
                accepted=True,
            )
            fitted.clear()
            self.assertEqual(
                service._train_page(engine, after=service.cursor_id, advance_cursor=True),
                "trained",
            )
            text = "\n".join(fitted)
            self.assertIn("in_flight", text)
            self.assertIn("after_hole", text)

    def test_a_weight_checkpoint_writes_adam_every_500_steps(self):
        self.assertEqual(ADAM_EVERY, 500)
        self.assertEqual(ADAM_EVERY % 20, 0)
        calls = []

        class Stub:
            def save(self, path, moments=True):
                calls.append(moments)

        with tempfile.TemporaryDirectory() as tmp:
            engine = make_engine(tmp, max_steps=0)
            engine.start()
            for index in range(8):
                _plant(engine, f"cadence-{index}", f"theorem t{index} : (0 = 0) := rfl\n")
            service = MiniLMService(Path(tmp) / "lm", type("W", (), {"context": 512})())
            service.trainer = Stub()
            service._fit = lambda docs: 0.1
            service.step = 19
            self.assertEqual(
                service._train_page(engine, after=0, advance_cursor=True),
                "trained",
            )
            self.assertEqual(calls, [False])
            service.step = 499
            self.assertEqual(
                service._train_page(engine, after=service.cursor_id, advance_cursor=True),
                "trained",
            )
            self.assertEqual(calls, [False, True])
            calls.clear()
            service.stop()
            self.assertEqual(calls, [True])

    def test_a_short_prefix_waits_for_four_proved_sentences(self):
        with tempfile.TemporaryDirectory() as tmp:
            engine = make_engine(tmp, max_steps=0)
            engine.start()
            _plant(engine, "only-one", "theorem only_one : (0 = 0) := rfl\n")
            _plant(engine, "still-open", "theorem still_open : (1 = 1) := rfl\n", proved=False)
            service = MiniLMService(Path(tmp) / "lm", type("W", (), {"context": 512})())
            fitted = []
            service._fit = lambda docs: fitted.extend(docs) or 0.1
            self.assertEqual(
                service._train_page(engine, after=0, advance_cursor=True),
                "waiting",
            )
            self.assertEqual(fitted, [])
            self.assertEqual(service.cursor_id, 0)
            self.assertEqual(service.step, 0)


def _plant(engine, stable_id: str, source: str, proved: bool = True) -> None:
    now = engine.store.now()
    engine.store.conn.execute(
        """
        INSERT INTO candidates (
          stable_id, run_id, canonical_ast_json, structural_hash, kind, provenance,
          current_status, curriculum_level, ancestor_stable_id, family, ast_size, depth,
          proof_method, dependency_depth, held_out, created_at, updated_at
        ) VALUES (?, 'run-1', '{}', ?, 'theorem', '{"origin": "generator"}',
          'unresolved', 1, NULL, 'eval_eq', 4, 1, 'rfl', 0, 0, ?, ?)
        """,
        (stable_id, stable_id, now, now),
    )
    row = engine.store.get_by_stable(stable_id)
    if proved:
        engine.store.insert_validation(
            candidate_id=row["id"],
            idempotency_key="val-" + stable_id,
            lean_version="fixture",
            toolchain_hash="fixture",
            validation_type="proof",
            result="accepted",
            accepted=True,
        )
    engine.queue.enqueue(
        "run-1",
        "lean_validate",
        payload={
            "candidate_id": row["id"],
            "source": source,
            "validation_type": "proof",
            "counterexample_id": None,
        },
        idempotency_key=f"run-1:lean_validate:{stable_id}:proof",
    )


class ModelTests(unittest.TestCase):
    def test_production_width_and_tiny_step(self):
        self.assertEqual(default_lean_workers(), 2)
        count = parameter_count(PRODUCTION)
        self.assertGreater(count, 48_000_000)
        self.assertLess(count, 55_000_000)
        trainer = Trainer(TINY, lr=1e-2)
        self.assertEqual(count_arrays(trainer.model), parameter_count(TINY))
        from theorem_gen.learn.minilm import encode

        row, length = encode("<|prove|>\ntheorem t : (0 = 0) := rfl\n<|end|>", TINY.context)
        first = trainer.step([row], [length])
        last = first
        for _ in range(25):
            last = trainer.step([row], [length])
        self.assertLess(last, first)

    def test_adam_moments_survive_a_reload(self):
        from theorem_gen.learn.minilm import encode

        trainer = Trainer(TINY, lr=1e-2)
        row, length = encode("<|prove|>\nt\n<|end|>", TINY.context)
        trainer.step([row], [length])
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "model.safetensors"
            trainer.save(path)
            restored = Trainer(TINY, lr=1e-2)
            restored.load(path)
            again = trainer.step([row], [length])
            kept = restored.step([row], [length])
        self.assertAlmostEqual(again, kept, places=5)

    def test_skipping_moments_leaves_the_adam_file(self):
        trainer = Trainer(TINY, lr=1e-2)
        from theorem_gen.learn.minilm import encode

        row, length = encode("<|prove|>\nt\n<|end|>", TINY.context)
        trainer.step([row], [length])
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "model.safetensors"
            trainer.save(path)
            adam = path.with_name("adam.safetensors")
            adam.write_bytes(b"kept")
            trainer.save(path, moments=False)
            self.assertEqual(adam.read_bytes(), b"kept")
            self.assertGreater(path.stat().st_size, 1000)

    def test_weights_without_adam_still_load(self):
        from theorem_gen.learn.minilm import encode

        trainer = Trainer(TINY, lr=1e-2)
        row, length = encode("<|prove|>\nt\n<|end|>", TINY.context)
        trainer.step([row], [length])
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "model.safetensors"
            trainer.model.save_weights(str(path))
            restored = Trainer(TINY, lr=1e-2)
            restored.load(path)
            restored.step([row], [length])

    def test_production_context_keeps_a_rich_proof(self):
        from theorem_gen.learn.minilm import decode, encode, role_documents
        from theorem_gen.richgen import rich_theorem

        self.assertEqual(PRODUCTION.context, 512)
        for index in (0, 3, 7):
            prove = role_documents(rich_theorem(1, index).source)[1]
            ids, length = encode(prove, PRODUCTION.context)
            shown = decode(ids[:length])
            self.assertIn("ac_rfl", shown)
            self.assertIn("<|end|>", shown)
            self.assertLessEqual(length, PRODUCTION.context)

    def test_engine_keeps_learning_false(self):
        with tempfile.TemporaryDirectory() as tmp:
            ticks = []

            class Fake:
                def tick(self, engine):
                    ticks.append(engine.run_id)

                def note_verdict(self, store, candidate):
                    return None

                def stop(self):
                    return None

            engine = make_engine(tmp, max_steps=1, lm=True, language=Fake())
            engine.start()
            self.assertGreaterEqual(len(ticks), 1)
            self.assertFalse(engine.status()["learning"])
            self.assertIn("lm_step", engine.status())


